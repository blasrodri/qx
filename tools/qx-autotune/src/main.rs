use anyhow::{Context, Result, bail};
use clap::Parser;
use qx_compiler::{
    PlanCandidateEvidence, PlanSelectionConstraints, PromotionTier, QualityMeasurement,
    ResidentMemoryMeasurement, TierMeasurement, select_execution_plan,
};
use serde::{Deserialize, Serialize};
use std::{fs, path::PathBuf, process::Command};

#[derive(Debug, Parser)]
#[command(
    name = "qx-autotune",
    about = "Select a sealed QX execution plan from measured promotion evidence"
)]
struct Args {
    /// JSON array of candidates with all four promotion-tier measurements.
    #[arg(long, conflicts_with = "suite")]
    evidence: Option<PathBuf>,
    /// Execute a candidate suite and produce complete-model evidence.
    #[arg(long, conflicts_with = "evidence")]
    suite: Option<PathBuf>,
    /// Keep evidence generated by --suite for audit/replay.
    #[arg(long)]
    write_evidence: Option<PathBuf>,
    /// Write the selected artifact-v2 execution-plan manifest here.
    #[arg(long)]
    output: PathBuf,
    /// Optional machine-readable selection report including rejected plans.
    #[arg(long)]
    report: Option<PathBuf>,
    #[arg(long, default_value_t = 0.01)]
    max_relative_ppl_delta: f64,
    #[arg(long, default_value_t = 0.02)]
    max_domain_relative_ppl_delta: f64,
    #[arg(long, default_value_t = 2.0)]
    max_task_delta_points: f64,
    /// Zero disables the physical-footprint gate during latency-only screening.
    #[arg(long, default_value_t = 0)]
    max_peak_physical_footprint_bytes: u64,
}

#[derive(Serialize)]
struct SelectionReport<'a> {
    selected_plan_id: &'a str,
    selected_complete_model_wall_ms_per_token: f64,
    selected_reason: &'static str,
    candidates: Vec<CandidateSummary>,
    rejected: &'a [(String, qx_compiler::CandidateRejection)],
}

#[derive(Serialize)]
struct CandidateSummary {
    plan_id: String,
    exact_semantics_verified: bool,
    complete_model_wall_ms_per_token: f64,
    complete_model_gpu_ms_per_token: f64,
    peak_physical_footprint_bytes: u64,
    quality_accepted: bool,
}

#[derive(Debug, Deserialize)]
struct CandidateSuite {
    schema_version: u32,
    qx_bench: PathBuf,
    fixtures: Vec<PathBuf>,
    #[serde(default = "default_rounds")]
    rounds: usize,
    #[serde(default = "default_warmup")]
    warmup: usize,
    candidates: Vec<CandidateRun>,
}

const fn default_rounds() -> usize {
    3
}

const fn default_warmup() -> usize {
    1
}

#[derive(Debug, Deserialize)]
struct CandidateRun {
    artifact: PathBuf,
    screening_tiers: Vec<TierMeasurement>,
    #[serde(default)]
    quality_gate: Option<PathBuf>,
    /// Optional reference artifact for exact transport/layout candidates.
    /// The runner verifies every quantized tensor decodes to identical codes
    /// and scales before allowing the candidate to use the exact-semantic
    /// quality path.
    #[serde(default)]
    exact_equivalent_to: Option<PathBuf>,
}

#[derive(Debug, Deserialize)]
struct QualityGateRecord {
    aggregate_relative_ppl_delta: f64,
    worst_domain_relative_ppl_delta: f64,
    human_eval_delta_points_vs_llama: Option<f64>,
    gsm8k_delta_points_vs_llama: Option<f64>,
    accepted: bool,
}

#[derive(Debug, Deserialize)]
struct BenchRecord {
    wall_ms_per_token: f64,
    gpu_ms_per_token: f64,
    current_rss_bytes: u64,
    peak_rss_bytes: u64,
    current_physical_footprint_bytes: u64,
    peak_physical_footprint_bytes: u64,
    known_metal_allocated_bytes: u64,
    mapped_artifact_bytes: u64,
    internal_cpu_waits: u64,
}

fn main() -> Result<()> {
    let args = Args::parse();
    let candidates = if let Some(path) = &args.evidence {
        serde_json::from_slice::<Vec<PlanCandidateEvidence>>(
            &fs::read(path).with_context(|| format!("read {}", path.display()))?,
        )
        .with_context(|| format!("parse {}", path.display()))?
    } else if let Some(path) = &args.suite {
        let suite = serde_json::from_slice::<CandidateSuite>(
            &fs::read(path).with_context(|| format!("read {}", path.display()))?,
        )
        .with_context(|| format!("parse {}", path.display()))?;
        let evidence = run_suite(&suite)?;
        if let Some(output) = &args.write_evidence {
            fs::write(output, serde_json::to_vec_pretty(&evidence)?)
                .with_context(|| format!("write {}", output.display()))?;
        }
        evidence
    } else {
        bail!("provide either --evidence or --suite");
    };
    let selection = select_execution_plan(
        &candidates,
        PlanSelectionConstraints {
            max_aggregate_relative_ppl_delta: args.max_relative_ppl_delta,
            max_domain_relative_ppl_delta: args.max_domain_relative_ppl_delta,
            max_task_delta_points: args.max_task_delta_points,
            max_peak_physical_footprint_bytes: args.max_peak_physical_footprint_bytes,
        },
    )?;
    fs::write(
        &args.output,
        serde_json::to_vec_pretty(&selection.selected)?,
    )
    .with_context(|| format!("write {}", args.output.display()))?;
    if let Some(report) = &args.report {
        let candidates_report = candidates
            .iter()
            .map(|candidate| {
                let complete = candidate
                    .tiers
                    .iter()
                    .find(|measurement| measurement.tier == PromotionTier::CompleteModel)
                    .expect("complete-model tier is added by run_suite or required by evidence");
                CandidateSummary {
                    plan_id: candidate.plan.plan_id.clone(),
                    exact_semantics_verified: candidate.exact_semantics_verified,
                    complete_model_wall_ms_per_token: complete.wall_ms_per_token,
                    complete_model_gpu_ms_per_token: complete.gpu_ms_per_token,
                    peak_physical_footprint_bytes: candidate.memory.peak_physical_footprint_bytes,
                    quality_accepted: candidate.quality.accepted
                        || candidate.exact_semantics_verified,
                }
            })
            .collect();
        let selected_complete_model_wall_ms_per_token = candidates
            .iter()
            .find(|candidate| candidate.plan.plan_id == selection.selected.plan_id)
            .and_then(|candidate| {
                candidate
                    .tiers
                    .iter()
                    .find(|measurement| measurement.tier == PromotionTier::CompleteModel)
            })
            .map(|measurement| measurement.wall_ms_per_token)
            .expect("selected plan has complete-model evidence");
        fs::write(
            report,
            serde_json::to_vec_pretty(&SelectionReport {
                selected_plan_id: &selection.selected.plan_id,
                selected_complete_model_wall_ms_per_token,
                selected_reason: "lowest measured complete-model wall latency after semantic, quality, memory, and promotion-tier gates",
                candidates: candidates_report,
                rejected: &selection.rejected,
            })?,
        )
        .with_context(|| format!("write {}", report.display()))?;
    }
    println!("selected plan: {}", selection.selected.plan_id);
    println!("rejected plans: {}", selection.rejected.len());
    Ok(())
}

fn run_suite(suite: &CandidateSuite) -> Result<Vec<PlanCandidateEvidence>> {
    if suite.schema_version != 1 || suite.rounds == 0 || suite.fixtures.is_empty() {
        bail!("candidate suite requires schema 1, positive rounds, and fixtures");
    }
    if suite.candidates.is_empty() {
        bail!("candidate suite has no artifacts");
    }
    for candidate in &suite.candidates {
        for tier in [
            PromotionTier::Kernel,
            PromotionTier::ProducerConsumer,
            PromotionTier::MultiLayer,
        ] {
            if !candidate
                .screening_tiers
                .iter()
                .any(|measurement| measurement.tier == tier)
            {
                bail!(
                    "candidate {} lacks {:?} screening evidence",
                    candidate.artifact.display(),
                    tier
                );
            }
        }
    }
    let mut records = (0..suite.candidates.len())
        .map(|_| Vec::<BenchRecord>::new())
        .collect::<Vec<_>>();
    let mut random = 0x5158_4155_544f_5455_u64;
    let mut run_index = 0_usize;
    for round in 0..suite.rounds {
        for fixture in &suite.fixtures {
            let mut order = (0..suite.candidates.len()).collect::<Vec<_>>();
            for index in (1..order.len()).rev() {
                random ^= random << 13;
                random ^= random >> 7;
                random ^= random << 17;
                order.swap(index, random as usize % (index + 1));
            }
            for candidate_index in order {
                let candidate = &suite.candidates[candidate_index];
                let result_path = std::env::temp_dir().join(format!(
                    "qx-autotune-{}-{round}-{run_index}.json",
                    std::process::id()
                ));
                run_index += 1;
                let status = Command::new(&suite.qx_bench)
                    .arg(&candidate.artifact)
                    .args(["--v2-token", "--fixture"])
                    .arg(fixture)
                    .args(["--warmup", &suite.warmup.to_string(), "--result-json"])
                    .arg(&result_path)
                    .status()
                    .with_context(|| format!("run {}", suite.qx_bench.display()))?;
                if !status.success() {
                    bail!(
                        "candidate {} failed on fixture {}",
                        candidate.artifact.display(),
                        fixture.display()
                    );
                }
                let record = serde_json::from_slice::<BenchRecord>(
                    &fs::read(&result_path)
                        .with_context(|| format!("read {}", result_path.display()))?,
                )?;
                let _ = fs::remove_file(&result_path);
                if record.internal_cpu_waits != 0 {
                    bail!(
                        "candidate {} performed internal CPU waits",
                        candidate.artifact.display()
                    );
                }
                records[candidate_index].push(record);
            }
        }
    }
    suite
        .candidates
        .iter()
        .zip(records)
        .map(|(candidate, mut measurements)| {
            measurements
                .sort_by(|left, right| left.wall_ms_per_token.total_cmp(&right.wall_ms_per_token));
            let wall = median(
                &measurements
                    .iter()
                    .map(|record| record.wall_ms_per_token)
                    .collect::<Vec<_>>(),
            );
            let gpu = median(
                &measurements
                    .iter()
                    .map(|record| record.gpu_ms_per_token)
                    .collect::<Vec<_>>(),
            );
            let artifact = qx_format::MappedArtifact::open(&candidate.artifact)
                .map_err(|error| anyhow::anyhow!(error.to_string()))?;
            let plan = artifact
                .info()
                .execution_plan
                .clone()
                .ok_or_else(|| anyhow::anyhow!("candidate artifact has no sealed plan"))?;
            let mut tiers = candidate.screening_tiers.clone();
            tiers.retain(|measurement| measurement.tier != PromotionTier::CompleteModel);
            tiers.push(TierMeasurement {
                tier: PromotionTier::CompleteModel,
                wall_ms_per_token: wall,
                gpu_ms_per_token: gpu,
            });
            let exact_semantics_verified = if let Some(reference) = &candidate.exact_equivalent_to {
                verify_exact_semantics(&candidate.artifact, reference)?;
                true
            } else {
                false
            };
            let quality_gate = candidate
                .quality_gate
                .as_ref()
                .map(|path| -> Result<QualityGateRecord> {
                    let bytes =
                        fs::read(path).with_context(|| format!("read {}", path.display()))?;
                    Ok(serde_json::from_slice::<QualityGateRecord>(&bytes)?)
                })
                .transpose()?;
            if quality_gate.is_none() && !exact_semantics_verified {
                bail!(
                    "candidate {} requires a triangular quality gate or exact_equivalent_to proof",
                    candidate.artifact.display()
                );
            }
            if let Some(quality_gate) = &quality_gate {
                if !quality_gate.accepted {
                    eprintln!(
                        "candidate {} carries a failed quality gate and will be rejected",
                        candidate.artifact.display()
                    );
                }
            }
            let quality_gate = quality_gate.unwrap_or(QualityGateRecord {
                aggregate_relative_ppl_delta: 0.0,
                worst_domain_relative_ppl_delta: 0.0,
                human_eval_delta_points_vs_llama: Some(0.0),
                gsm8k_delta_points_vs_llama: Some(0.0),
                accepted: true,
            });
            Ok(PlanCandidateEvidence {
                plan,
                tiers,
                quality: QualityMeasurement {
                    accepted: quality_gate.accepted,
                    aggregate_relative_ppl_delta_vs_llama: quality_gate
                        .aggregate_relative_ppl_delta,
                    maximum_domain_relative_ppl_delta_vs_llama: quality_gate
                        .worst_domain_relative_ppl_delta,
                    human_eval_delta_points_vs_llama: quality_gate.human_eval_delta_points_vs_llama,
                    gsm8k_delta_points_vs_llama: quality_gate.gsm8k_delta_points_vs_llama,
                },
                memory: ResidentMemoryMeasurement {
                    current_rss_bytes: max_field(&measurements, |record| record.current_rss_bytes),
                    peak_rss_bytes: max_field(&measurements, |record| record.peak_rss_bytes),
                    current_physical_footprint_bytes: max_field(&measurements, |record| {
                        record.current_physical_footprint_bytes
                    }),
                    peak_physical_footprint_bytes: max_field(&measurements, |record| {
                        record.peak_physical_footprint_bytes
                    }),
                    known_metal_bytes: max_field(&measurements, |record| {
                        record.known_metal_allocated_bytes
                    }),
                    mapped_model_bytes: max_field(&measurements, |record| {
                        record.mapped_artifact_bytes
                    }),
                },
                exact_semantics_verified,
            })
        })
        .collect()
}

fn verify_exact_semantics(candidate_path: &PathBuf, reference_path: &PathBuf) -> Result<()> {
    let candidate = qx_format::MappedArtifact::open(candidate_path)
        .map_err(|error| anyhow::anyhow!(error.to_string()))?;
    let reference = qx_format::MappedArtifact::open(reference_path)
        .map_err(|error| anyhow::anyhow!(error.to_string()))?;
    let candidate_plan = candidate
        .info()
        .execution_plan
        .as_ref()
        .ok_or_else(|| anyhow::anyhow!("candidate artifact has no execution plan"))?;
    let reference_plan = reference
        .info()
        .execution_plan
        .as_ref()
        .ok_or_else(|| anyhow::anyhow!("reference artifact has no execution plan"))?;
    let compatible_expert_layout =
        |candidate: qx_format::ExpertRepresentation, reference: qx_format::ExpertRepresentation| {
            candidate == reference
                || matches!(
                    (candidate, reference),
                    (
                        qx_format::ExpertRepresentation::Group32Q4RowInline,
                        qx_format::ExpertRepresentation::Group32Q4RowMajor
                    ) | (
                        qx_format::ExpertRepresentation::Group32Q4RowMajor,
                        qx_format::ExpertRepresentation::Group32Q4RowInline
                    )
                )
        };
    if candidate_plan.model_id != reference_plan.model_id
        || candidate_plan.target != reference_plan.target
        || candidate_plan.workload != reference_plan.workload
        || candidate_plan.topology != reference_plan.topology
        || candidate_plan.schedule != reference_plan.schedule
        || candidate_plan.sparse_experts != reference_plan.sparse_experts
        || candidate_plan.memory != reference_plan.memory
        || candidate_plan.representations.dense != reference_plan.representations.dense
        || !compatible_expert_layout(
            candidate_plan.representations.gate_up,
            reference_plan.representations.gate_up,
        )
        || !compatible_expert_layout(
            candidate_plan.representations.down,
            reference_plan.representations.down,
        )
    {
        bail!("exact-equivalence artifacts differ outside expert transport layout");
    }
    if candidate.info().entries.len() != reference.info().entries.len() {
        bail!("exact-equivalence artifacts have different tensor counts");
    }
    for (reference_index, reference_entry) in reference.info().entries.iter().enumerate() {
        let candidate_index = candidate
            .info()
            .entries
            .iter()
            .position(|entry| {
                entry.layer == reference_entry.layer
                    && entry.expert == reference_entry.expert
                    && entry.kind == reference_entry.kind
            })
            .ok_or_else(|| anyhow::anyhow!("candidate is missing a matching tensor entry"))?;
        let candidate_entry = &candidate.info().entries[candidate_index];
        let layout_compatible = candidate_entry.layout == reference_entry.layout
            || (matches!(
                reference_entry.kind,
                qx_format::TensorKind::GateUp | qx_format::TensorKind::Down
            ) && matches!(
                (reference_entry.layout, candidate_entry.layout),
                (
                    qx_quant::PackingLayout::RowMajor,
                    qx_quant::PackingLayout::Q4RowInline
                ) | (
                    qx_quant::PackingLayout::Q4RowInline,
                    qx_quant::PackingLayout::RowMajor
                )
            ));
        if candidate_entry.quant_type != reference_entry.quant_type
            || candidate_entry.rows != reference_entry.rows
            || candidate_entry.cols != reference_entry.cols
            || candidate_entry.group_size != reference_entry.group_size
            || !layout_compatible
        {
            bail!("exact-equivalence tensor metadata differs");
        }
        let reference_tensor = reference
            .quantized_tensor(reference_index)
            .map_err(|error| anyhow::anyhow!(error.to_string()))?;
        let candidate_tensor = candidate
            .quantized_tensor(candidate_index)
            .map_err(|error| anyhow::anyhow!(error.to_string()))?;
        if reference_tensor.quant_type != candidate_tensor.quant_type
            || reference_tensor.rows != candidate_tensor.rows
            || reference_tensor.cols != candidate_tensor.cols
            || reference_tensor.group_size != candidate_tensor.group_size
            || reference_tensor.data != candidate_tensor.data
            || reference_tensor.scales != candidate_tensor.scales
        {
            bail!("exact-equivalence tensor values differ");
        }
    }
    Ok(())
}

fn median(values: &[f64]) -> f64 {
    let mut values = values.to_vec();
    values.sort_by(f64::total_cmp);
    let middle = values.len() / 2;
    if values.len() % 2 == 0 {
        (values[middle - 1] + values[middle]) / 2.0
    } else {
        values[middle]
    }
}

fn max_field(records: &[BenchRecord], field: impl Fn(&BenchRecord) -> u64) -> u64 {
    records.iter().map(field).max().unwrap_or(0)
}
