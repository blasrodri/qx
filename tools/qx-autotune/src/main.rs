use anyhow::{Context, Result, bail};
use clap::Parser;
use qx_compiler::{
    PlanCandidateEvidence, PlanSelectionConstraints, PromotionTier, QualityMeasurement,
    ResidentMemoryMeasurement, TierMeasurement, select_execution_plan,
};
use serde::{Deserialize, Serialize};
use std::{fs, path::PathBuf, process::Command};

#[derive(Debug, Parser)]
#[command(
    name = "qx-autotune",
    about = "Select a sealed QX execution plan from measured promotion evidence"
)]
struct Args {
    /// JSON array of candidates with all four promotion-tier measurements.
    #[arg(long, conflicts_with = "suite")]
    evidence: Option<PathBuf>,
    /// Execute a candidate suite and produce complete-model evidence.
    #[arg(long, conflicts_with = "evidence")]
    suite: Option<PathBuf>,
    /// Keep evidence generated by --suite for audit/replay.
    #[arg(long)]
    write_evidence: Option<PathBuf>,
    /// Write the selected artifact-v2 execution-plan manifest here.
    #[arg(long)]
    output: PathBuf,
    /// Optional machine-readable selection report including rejected plans.
    #[arg(long)]
    report: Option<PathBuf>,
    #[arg(long, default_value_t = 0.01)]
    max_relative_ppl_delta: f64,
    #[arg(long, default_value_t = 0.02)]
    max_domain_relative_ppl_delta: f64,
    #[arg(long, default_value_t = 2.0)]
    max_task_delta_points: f64,
    /// Zero disables the physical-footprint gate during latency-only screening.
    #[arg(long, default_value_t = 0)]
    max_peak_physical_footprint_bytes: u64,
}

#[derive(Serialize)]
struct SelectionReport<'a> {
    selected_plan_id: &'a str,
    rejected: &'a [(String, qx_compiler::CandidateRejection)],
}

#[derive(Debug, Deserialize)]
struct CandidateSuite {
    schema_version: u32,
    qx_bench: PathBuf,
    fixtures: Vec<PathBuf>,
    #[serde(default = "default_rounds")]
    rounds: usize,
    #[serde(default = "default_warmup")]
    warmup: usize,
    candidates: Vec<CandidateRun>,
}

const fn default_rounds() -> usize {
    3
}

const fn default_warmup() -> usize {
    1
}

#[derive(Debug, Deserialize)]
struct CandidateRun {
    artifact: PathBuf,
    screening_tiers: Vec<TierMeasurement>,
    quality_gate: PathBuf,
}

#[derive(Debug, Deserialize)]
struct QualityGateRecord {
    aggregate_relative_ppl_delta: f64,
    worst_domain_relative_ppl_delta: f64,
    human_eval_delta_points_vs_llama: Option<f64>,
    gsm8k_delta_points_vs_llama: Option<f64>,
    accepted: bool,
}

#[derive(Debug, Deserialize)]
struct BenchRecord {
    wall_ms_per_token: f64,
    gpu_ms_per_token: f64,
    current_rss_bytes: u64,
    peak_rss_bytes: u64,
    current_physical_footprint_bytes: u64,
    peak_physical_footprint_bytes: u64,
    known_metal_allocated_bytes: u64,
    mapped_artifact_bytes: u64,
    internal_cpu_waits: u64,
}

fn main() -> Result<()> {
    let args = Args::parse();
    let candidates = if let Some(path) = &args.evidence {
        serde_json::from_slice::<Vec<PlanCandidateEvidence>>(
            &fs::read(path).with_context(|| format!("read {}", path.display()))?,
        )
        .with_context(|| format!("parse {}", path.display()))?
    } else if let Some(path) = &args.suite {
        let suite = serde_json::from_slice::<CandidateSuite>(
            &fs::read(path).with_context(|| format!("read {}", path.display()))?,
        )
        .with_context(|| format!("parse {}", path.display()))?;
        let evidence = run_suite(&suite)?;
        if let Some(output) = &args.write_evidence {
            fs::write(output, serde_json::to_vec_pretty(&evidence)?)
                .with_context(|| format!("write {}", output.display()))?;
        }
        evidence
    } else {
        bail!("provide either --evidence or --suite");
    };
    let selection = select_execution_plan(
        &candidates,
        PlanSelectionConstraints {
            max_aggregate_relative_ppl_delta: args.max_relative_ppl_delta,
            max_domain_relative_ppl_delta: args.max_domain_relative_ppl_delta,
            max_task_delta_points: args.max_task_delta_points,
            max_peak_physical_footprint_bytes: args.max_peak_physical_footprint_bytes,
        },
    )?;
    fs::write(
        &args.output,
        serde_json::to_vec_pretty(&selection.selected)?,
    )
    .with_context(|| format!("write {}", args.output.display()))?;
    if let Some(report) = &args.report {
        fs::write(
            report,
            serde_json::to_vec_pretty(&SelectionReport {
                selected_plan_id: &selection.selected.plan_id,
                rejected: &selection.rejected,
            })?,
        )
        .with_context(|| format!("write {}", report.display()))?;
    }
    println!("selected plan: {}", selection.selected.plan_id);
    println!("rejected plans: {}", selection.rejected.len());
    Ok(())
}

fn run_suite(suite: &CandidateSuite) -> Result<Vec<PlanCandidateEvidence>> {
    if suite.schema_version != 1 || suite.rounds == 0 || suite.fixtures.is_empty() {
        bail!("candidate suite requires schema 1, positive rounds, and fixtures");
    }
    if suite.candidates.is_empty() {
        bail!("candidate suite has no artifacts");
    }
    for candidate in &suite.candidates {
        for tier in [
            PromotionTier::Kernel,
            PromotionTier::ProducerConsumer,
            PromotionTier::MultiLayer,
        ] {
            if !candidate
                .screening_tiers
                .iter()
                .any(|measurement| measurement.tier == tier)
            {
                bail!(
                    "candidate {} lacks {:?} screening evidence",
                    candidate.artifact.display(),
                    tier
                );
            }
        }
    }
    let mut records = (0..suite.candidates.len())
        .map(|_| Vec::<BenchRecord>::new())
        .collect::<Vec<_>>();
    let mut random = 0x5158_4155_544f_5455_u64;
    let mut run_index = 0_usize;
    for round in 0..suite.rounds {
        for fixture in &suite.fixtures {
            let mut order = (0..suite.candidates.len()).collect::<Vec<_>>();
            for index in (1..order.len()).rev() {
                random ^= random << 13;
                random ^= random >> 7;
                random ^= random << 17;
                order.swap(index, random as usize % (index + 1));
            }
            for candidate_index in order {
                let candidate = &suite.candidates[candidate_index];
                let result_path = std::env::temp_dir().join(format!(
                    "qx-autotune-{}-{round}-{run_index}.json",
                    std::process::id()
                ));
                run_index += 1;
                let status = Command::new(&suite.qx_bench)
                    .arg(&candidate.artifact)
                    .args(["--v2-token", "--fixture"])
                    .arg(fixture)
                    .args(["--warmup", &suite.warmup.to_string(), "--result-json"])
                    .arg(&result_path)
                    .status()
                    .with_context(|| format!("run {}", suite.qx_bench.display()))?;
                if !status.success() {
                    bail!(
                        "candidate {} failed on fixture {}",
                        candidate.artifact.display(),
                        fixture.display()
                    );
                }
                let record = serde_json::from_slice::<BenchRecord>(
                    &fs::read(&result_path)
                        .with_context(|| format!("read {}", result_path.display()))?,
                )?;
                let _ = fs::remove_file(&result_path);
                if record.internal_cpu_waits != 0 {
                    bail!(
                        "candidate {} performed internal CPU waits",
                        candidate.artifact.display()
                    );
                }
                records[candidate_index].push(record);
            }
        }
    }
    suite
        .candidates
        .iter()
        .zip(records)
        .map(|(candidate, mut measurements)| {
            measurements
                .sort_by(|left, right| left.wall_ms_per_token.total_cmp(&right.wall_ms_per_token));
            let wall = median(
                &measurements
                    .iter()
                    .map(|record| record.wall_ms_per_token)
                    .collect::<Vec<_>>(),
            );
            let gpu = median(
                &measurements
                    .iter()
                    .map(|record| record.gpu_ms_per_token)
                    .collect::<Vec<_>>(),
            );
            let artifact = qx_format::MappedArtifact::open(&candidate.artifact)
                .map_err(|error| anyhow::anyhow!(error.to_string()))?;
            let plan = artifact
                .info()
                .execution_plan
                .clone()
                .ok_or_else(|| anyhow::anyhow!("candidate artifact has no sealed plan"))?;
            let mut tiers = candidate.screening_tiers.clone();
            tiers.retain(|measurement| measurement.tier != PromotionTier::CompleteModel);
            tiers.push(TierMeasurement {
                tier: PromotionTier::CompleteModel,
                wall_ms_per_token: wall,
                gpu_ms_per_token: gpu,
            });
            let quality_gate = serde_json::from_slice::<QualityGateRecord>(
                &fs::read(&candidate.quality_gate)
                    .with_context(|| format!("read {}", candidate.quality_gate.display()))?,
            )?;
            if !quality_gate.accepted {
                eprintln!(
                    "candidate {} carries a failed quality gate and will be rejected",
                    candidate.artifact.display()
                );
            }
            Ok(PlanCandidateEvidence {
                plan,
                tiers,
                quality: QualityMeasurement {
                    accepted: quality_gate.accepted,
                    aggregate_relative_ppl_delta_vs_llama: quality_gate
                        .aggregate_relative_ppl_delta,
                    maximum_domain_relative_ppl_delta_vs_llama: quality_gate
                        .worst_domain_relative_ppl_delta,
                    human_eval_delta_points_vs_llama: quality_gate.human_eval_delta_points_vs_llama,
                    gsm8k_delta_points_vs_llama: quality_gate.gsm8k_delta_points_vs_llama,
                },
                memory: ResidentMemoryMeasurement {
                    current_rss_bytes: max_field(&measurements, |record| record.current_rss_bytes),
                    peak_rss_bytes: max_field(&measurements, |record| record.peak_rss_bytes),
                    current_physical_footprint_bytes: max_field(&measurements, |record| {
                        record.current_physical_footprint_bytes
                    }),
                    peak_physical_footprint_bytes: max_field(&measurements, |record| {
                        record.peak_physical_footprint_bytes
                    }),
                    known_metal_bytes: max_field(&measurements, |record| {
                        record.known_metal_allocated_bytes
                    }),
                    mapped_model_bytes: max_field(&measurements, |record| {
                        record.mapped_artifact_bytes
                    }),
                },
            })
        })
        .collect()
}

fn median(values: &[f64]) -> f64 {
    let mut values = values.to_vec();
    values.sort_by(f64::total_cmp);
    let middle = values.len() / 2;
    if values.len() % 2 == 0 {
        (values[middle - 1] + values[middle]) / 2.0
    } else {
        values[middle]
    }
}

fn max_field(records: &[BenchRecord], field: impl Fn(&BenchRecord) -> u64) -> u64 {
    records.iter().map(field).max().unwrap_or(0)
}
